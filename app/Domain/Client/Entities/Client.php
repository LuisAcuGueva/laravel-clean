<?php

namespace App\Domain\Client\Entities;

use InvalidArgumentException;

final class Client
{
    private function __construct(
        private ?int $id,
        private string $name,
        private string $email,
        private ?string $phone,
        private ?string $address,
    ) {}

    /**
     * Create a new client that has not been persisted yet.
     */
    public static function create(string $name, string $email, ?string $phone, ?string $address): self
    {
        return new self(null, self::normalizeName($name), self::normalizeEmail($email), $phone, $address);
    }

    /**
     * Rebuild an existing client from persisted data.
     */
    public static function reconstitute(int $id, string $name, string $email, ?string $phone, ?string $address): self
    {
        return new self($id, self::normalizeName($name), self::normalizeEmail($email), $phone, $address);
    }

    /**
     * Replace the editable data of this client.
     */
    public function update(string $name, string $email, ?string $phone, ?string $address): void
    {
        $this->name = self::normalizeName($name);
        $this->email = self::normalizeEmail($email);
        $this->phone = $phone;
        $this->address = $address;
    }

    /**
     * Assign the identifier generated by the persistence layer.
     */
    public function assignId(int $id): void
    {
        if ($this->id !== null) {
            throw new InvalidArgumentException('El cliente ya tiene un identificador asignado.');
        }

        $this->id = $id;
    }

    public function id(): ?int
    {
        return $this->id;
    }

    public function name(): string
    {
        return $this->name;
    }

    public function email(): string
    {
        return $this->email;
    }

    public function phone(): ?string
    {
        return $this->phone;
    }

    public function address(): ?string
    {
        return $this->address;
    }

    private static function normalizeName(string $name): string
    {
        $name = trim($name);

        if ($name === '') {
            throw new InvalidArgumentException('El nombre del cliente no puede estar vacío.');
        }

        return $name;
    }

    private static function normalizeEmail(string $email): string
    {
        return strtolower(trim($email));
    }
}
